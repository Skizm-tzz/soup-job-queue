"""Regenerate results/INDEX.md from every run directory, including aborted runs.

Run:  python -m chaos.index   (the harness also calls it after every run)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def _load(p: Path) -> dict | None:
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def write(results: Path) -> None:
    rows = []
    for d in sorted(p for p in results.iterdir() if p.is_dir()):
        cfg = _load(d / "config.json")
        if cfg is None:
            continue
        s = _load(d / "summary.json") or {}
        exp = cfg["expected"]
        exp_s = exp["verdict"] + (f" ({','.join(exp['invariants'])})" if exp.get("invariants") else "")
        if not s.get("completed"):
            got = "ABORTED" + (f": {s['harness_error'][:60]}" if s.get("harness_error") else " (no summary)")
            ok = "-"
            cov = ""
        else:
            failed = s["failed_invariants"]
            got = s["verdict"] + (f" ({','.join(failed)})" if failed else "")
            if s.get("not_covered"):
                got += f" not covered: {','.join(s['not_covered'])}"
            ok = "yes" if s["as_expected"] else "**NO**"
            c = s["coverage"]
            cov = (f"kills {c['kills']}, takeovers {c['takeovers']}, stale rejected {c['stale_completes_rejected']}, "
                   f"cancel running {c['cancelled_from_running']}, exhausted {c['attempts_exhausted']}")
        rows.append(f"| [{d.name}]({d.name}/) | {cfg['label']} | {cfg['scenario']} | {cfg['seed']} | "
                    f"{cfg['params']['jobs']} | {','.join(cfg['flags']) or '-'} | {cfg['isolation']} | "
                    f"{exp_s} | {got} | {ok} | {cov} | {(cfg.get('git_commit') or '')[:7]} |")
    text = [
        "# Chaos runs",
        "",
        "Generated by `python -m chaos.index` from every `results/<run>/` directory; nothing is removed.",
        "A run without `summary.json` was aborted and is listed as such.",
        "",
        "| run | label | scenario | seed | jobs | seeded bug | isolation | expected | got | as expected | coverage | commit |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
        *rows,
        "",
        f"{len(rows)} runs.",
        "",
    ]
    (results / "INDEX.md").write_text("\n".join(text), encoding="utf-8")


if __name__ == "__main__":
    write(Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "results")
